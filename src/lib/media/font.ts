const glyph = (c: string) => (G[c] ?? G[c.toUpperCase()] ?? G["?"]).split("|");

export type TextMask = { width: number; height: number; mask: Uint8Array };

/** Rasterise text into a 0/1 mask; each font pixel becomes a `cell`×`cell` square, 1 cell between glyphs. */
export function textMask(text: string, cell: number): TextMask {
  const chars = [...text];
  const width = Math.max(1, (chars.length * 6 - 1) * cell);
  const height = 7 * cell;
  const mask = new Uint8Array(width * height);
  chars.forEach((c, ci) => {
    const rows = glyph(c);
    for (let gy = 0; gy < 7; gy++) {
      for (let gx = 0; gx < 5; gx++) {
        if (rows[gy][gx] !== "#") continue;
        const x0 = (ci * 6 + gx) * cell;
        const y0 = gy * cell;
        for (let y = y0; y < y0 + cell; y++) mask.fill(1, y * width + x0, y * width + x0 + cell);
      }
    }
  });
  return { width, height, mask };
}
